"""Build the Auto Ontology server kit: compose file, .env, setup script.

Secrets (Postgres password, admin password, auth secret) are generated once
and kept in Ontology Export Settings, so downloading the kit again produces
the same .env and never locks you out of a running server.
"""

from __future__ import annotations

import io
import os
import zipfile
from datetime import datetime
from urllib.parse import urlparse

from frappe2ontology.readonly import generate_password

DEPLOY_DIR = os.path.join(os.path.dirname(__file__), "deploy")

PROVIDERS = {
    "NVIDIA (build.nvidia.com)": (
        "https://integrate.api.nvidia.com/v1",
        "nvidia/nemotron-3.5-lightning-30b-a3b",
    ),
    "Google Gemini": ("https://generativelanguage.googleapis.com/v1beta/openai", "gemini-2.5-flash"),
    "Other OpenAI-compatible": ("", ""),
}
NVIDIA_ENDPOINT = "https://integrate.api.nvidia.com/v1"
EMBED_MODEL = "nvidia/nemotron-3.5-embed-1b"
RERANK_ENDPOINT = (
    "https://ai.api.nvidia.com/v1/retrieval/nvidia/nemotron-3.5-rerank-8b/reranking"
)
RERANK_MODEL = "nvidia/nemotron-3.5-rerank-8b"


class KitError(ValueError):
    pass


def network_plan(app_url: str) -> dict:
    """How the web app is exposed, from the URL people will open."""
    parsed = urlparse(app_url)
    if parsed.scheme not in ("http", "https") or not parsed.hostname:
        raise KitError("Auto Ontology URL must look like https://ontology.example.com")
    host = parsed.hostname
    local = host in ("localhost", "127.0.0.1")
    if parsed.scheme == "https" and not local:
        return {"profiles": "https", "bind": "127.0.0.1", "domain": host, "mode": "https"}
    if local:
        return {"profiles": "", "bind": "127.0.0.1", "domain": "", "mode": "local"}
    return {"profiles": "", "bind": "0.0.0.0", "domain": "", "mode": "plain-http"}


def ensure_secrets(values: dict) -> dict:
    """Fill any missing generated secret; returns the ones that were created."""
    created = {}
    for key, length in (("kit_postgres_password", 32), ("kit_admin_password", 20), ("kit_auth_secret", 48)):
        if not values.get(key):
            values[key] = created[key] = generate_password(length)
    return created


def render_env(v: dict) -> str:
    """``v`` holds plain values (passwords already decrypted)."""
    for key, label in (("app_url", "Auto Ontology URL"), ("admin_email", "Auto Ontology Admin Email"),
                       ("nvidia_api_key", "NVIDIA API Key")):
        if not v.get(key):
            raise KitError(f"Set {label} first.")
    endpoint = v.get("llm_endpoint") or PROVIDERS.get(v.get("llm_provider"), ("", ""))[0]
    model = v.get("llm_model") or PROVIDERS.get(v.get("llm_provider"), ("", ""))[1]
    llm_key = v.get("llm_api_key") or (v["nvidia_api_key"] if endpoint == NVIDIA_ENDPOINT else "")
    if not (endpoint and model and llm_key):
        raise KitError("Set the chat model endpoint, name and API key first.")
    plan = network_plan(v["app_url"])
    lines = [
        f"# Auto Ontology for ERPNext site {v.get('site', '')}",
        f"# Generated by Frappe2Ontology on {datetime.now():%Y-%m-%d %H:%M}. Keep this file private.",
        "",
        "# --- Deployment",
        f"AUTO_ONTOLOGY_REF={v.get('auto_ontology_ref') or 'main'}",
        f"COMPOSE_PROFILES={plan['profiles']}",
        f"AO_BIND={plan['bind']}",
        f"DOMAIN={plan['domain']}",
        f"APP_URL={v['app_url'].rstrip('/')}",
        "AUTO_ONTOLOGY_MCP_PUBLIC_URL=http://localhost:3003",
        "",
        "# --- Internal database (inside Docker only)",
        "POSTGRES_HOST=postgres",
        "POSTGRES_PORT=5432",
        "POSTGRES_USER=postgres",
        f"POSTGRES_PASSWORD={v['kit_postgres_password']}",
        "POSTGRES_DATABASE=auto_ontology",
        "",
        "# --- Sign-in",
        f"AUTO_ONTOLOGY_ADMIN_EMAIL={v['admin_email']}",
        f"AUTO_ONTOLOGY_ADMIN_PASSWORD={v['kit_admin_password']}",
        f"AUTH_SECRET={v['kit_auth_secret']}",
        "",
        "# --- Source databases: left empty on purpose. ERPNext adds the connection",
        "# itself when you click Push to Auto Ontology, after importing the model.",
        "CONNECTION_STRINGS=",
        "INGESTION_SERVICE_URL=http://ingestion-service:3002",
        "",
        "# --- Models",
        f"DEFAULT_MODELS_ENDPOINT={endpoint}",
        f"DEFAULT_MODELS_API_KEY={llm_key}",
        f"DEFAULT_MODELS_MODEL={model}",
        f"REASONING_ENDPOINT={endpoint}",
        f"REASONING_API_KEY={llm_key}",
        f"REASONING_MODEL={model}",
        f"NON_REASONING_ENDPOINT={endpoint}",
        f"NON_REASONING_API_KEY={llm_key}",
        f"NON_REASONING_MODEL={model}",
        "# Embeddings and reranking stay on NVIDIA: Auto Ontology's vector index is",
        "# sized for this model. Ingest and query must use the same one.",
        f"EMBED_ENDPOINT={NVIDIA_ENDPOINT}",
        f"EMBED_API_KEY={v['nvidia_api_key']}",
        f"EMBED_MODEL={EMBED_MODEL}",
        f"RERANK_ENDPOINT={RERANK_ENDPOINT}",
        f"RERANK_API_KEY={v['nvidia_api_key']}",
        f"RERANK_MODEL={RERANK_MODEL}",
        "",
    ]
    return "\n".join(lines)


_README = """\
Auto Ontology server kit for {site}
{underline}

Generated by Frappe2Ontology on {date}. The .env file holds passwords and API
keys: keep this folder private (chmod 600 .env).

Requirements
------------
* A Linux server with Docker Engine and Docker Compose v2, git and curl.
  4 CPU / 8 GB RAM / 30 GB disk is a comfortable minimum.
* Outbound HTTPS to github.com, Docker Hub and your model provider.
{https_req}
Install
-------
    unzip auto-ontology-kit.zip -d auto-ontology-kit && cd auto-ontology-kit
    chmod 600 .env && ./setup.sh

Then open {app_url} and sign in as {admin_email} with the password in .env
(AUTO_ONTOLOGY_ADMIN_PASSWORD). Create an API token (user menu > API Tokens)
and paste it into ERPNext > Ontology Export Settings > API Token.

Let Auto Ontology reach this ERPNext database
---------------------------------------------
1. On the ERPNext server, create the read-only database user:

       bench --site {site} ontology-readonly-user

2. MariaDB must accept connections from the Auto Ontology server.
{db_note}
3. In ERPNext click Check Setup, then Push to Auto Ontology.

Security
--------
* Only the web app is exposed ({exposure}). The backend and ingestion
  services trust whoever calls them, so this kit never publishes them; do
  not add ports for 3001 or 3002.
* The database user can only SELECT the exported tables.
* Keep Settings > Semantic Compilation OFF for the first pilot: the model
  from ERPNext is the source of truth.

Day to day
----------
    ./setup.sh status | logs | stop
    ./setup.sh            # update to AUTO_ONTOLOGY_REF in .env

This kit builds NVIDIA Auto Ontology (Apache-2.0, https://github.com/NVIDIA/auto-ontology).
"""


def render_readme(v: dict) -> str:
    plan = network_plan(v["app_url"])
    if plan["mode"] == "https":
        https_req = (
            f"* DNS: {plan['domain']} must point at this server, with ports 80 and 443 open.\n"
            "  Caddy gets the HTTPS certificate automatically.\n"
        )
        exposure = f"https://{plan['domain']} through Caddy"
    elif plan["mode"] == "local":
        https_req = ""
        exposure = "http://127.0.0.1:3000, this machine only"
    else:
        https_req = (
            "* WARNING: the URL is plain http, so API tokens and passwords cross the\n"
            "  network unencrypted. Prefer an https:// URL with a domain name.\n"
        )
        exposure = "port 3000 on all interfaces; restrict it with a firewall"
    if (v.get("ro_db_host") or "") in ("host.docker.internal", "172.17.0.1"):
        db_note = (
            "   Auto Ontology runs on the same server as MariaDB and connects to\n"
            "   host.docker.internal. MariaDB usually listens on 127.0.0.1 only, so add\n"
            "   the Docker bridge address in /etc/mysql/mariadb.conf.d/50-server.cnf:\n\n"
            "       bind-address = 127.0.0.1,172.17.0.1\n\n"
            "   then: sudo systemctl restart mariadb\n"
            "   (Multiple addresses need MariaDB 10.11 or later; on older versions use\n"
            "   0.0.0.0 and firewall port 3306 to the Docker network.)\n"
        )
    else:
        db_note = (
            f"   Auto Ontology connects to {v.get('ro_db_host')}:{v.get('ro_db_port') or 3306}.\n"
            "   Make MariaDB listen on that address (bind-address) and allow only the\n"
            "   Auto Ontology server through the firewall on that port.\n"
        )
    title = f"Auto Ontology server kit for {v.get('site', '')}"
    return _README.format(
        site=v.get("site", ""),
        underline="=" * len(title),
        date=f"{datetime.now():%Y-%m-%d}",
        https_req=https_req,
        app_url=v["app_url"],
        admin_email=v["admin_email"],
        db_note=db_note,
        exposure=exposure,
    )


def build_zip(v: dict) -> bytes:
    env = render_env(v)
    readme = render_readme(v)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in ("docker-compose.yml", "Caddyfile"):
            with open(os.path.join(DEPLOY_DIR, name), encoding="utf-8") as handle:
                archive.writestr(name, handle.read())
        with open(os.path.join(DEPLOY_DIR, "setup.sh"), encoding="utf-8") as handle:
            info = zipfile.ZipInfo("setup.sh", date_time=datetime.now().timetuple()[:6])
            info.external_attr = 0o755 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, handle.read())
        env_info = zipfile.ZipInfo(".env", date_time=datetime.now().timetuple()[:6])
        env_info.external_attr = 0o600 << 16
        env_info.compress_type = zipfile.ZIP_DEFLATED
        archive.writestr(env_info, env)
        archive.writestr("README.txt", readme)
    return buffer.getvalue()
